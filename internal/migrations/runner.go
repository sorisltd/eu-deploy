package migrations

import (
	"fmt"
	"strings"
)

// ArchiveName and RunnerName are the file names used next to each other on the
// remote host (release folder during deploy, a scratch folder for `eu migrate`).
const (
	ArchiveName = "migrations.tar.gz"
	RunnerName  = "migrate.sh"
	// ResultPrefix starts the one machine-readable line the runner prints on stdout:
	// result <mode> <applied> <pending> <ran> <backup-path-or-->
	ResultPrefix = "eu-migrate-result"
)

// RunnerOptions say where the database is on the remote host.
type RunnerOptions struct {
	Container   string // docker container running Postgres
	Database    string
	User        string
	Backup      bool
	BackupDir   string // on the remote host
	KeepBackups int
}

func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", `'"'"'`) + "'"
}

// RenderRunner returns a bash script that runs on the remote host from the
// folder holding ArchiveName. Usage:
//
//	bash migrate.sh status
//	bash migrate.sh apply              # EU_MIGRATE_WHO labels the bookkeeping rows
//	bash migrate.sh baseline [through] # mark files (up to and including `through`) as applied
func RenderRunner(files []File, o RunnerOptions) string {
	keep := o.KeepBackups
	if keep <= 0 {
		keep = 10
	}
	backup := "0"
	if o.Backup {
		backup = "1"
	}
	var manifest strings.Builder
	for _, f := range files {
		fmt.Fprintf(&manifest, "%s\t%s\t%t\t%t\n", f.Name, f.SHA256, f.OwnTx, f.Destructive)
	}

	return fmt.Sprintf(`#!/usr/bin/env bash
# Generated by eu-deploy. Applies SQL migrations recorded in public.schema_migrations.
set -euo pipefail
MODE="${1:-status}"
THROUGH="${2:-}"
CONTAINER=%s
DB=%s
DBUSER=%s
BACKUP=%s
BACKUP_DIR=%s
KEEP=%d
WHO="${EU_MIGRATE_WHO:-eu migrate}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

log() { printf '%%s\n' "$*" >&2; }
die() { log "ERROR: $*"; exit 1; }
result() { printf '%s\t%%s\t%%s\t%%s\t%%s\t%%s\n' "$MODE" "$1" "$2" "$3" "${4:--}"; }

docker ps --format '{{.Names}}' | grep -Fx -- "$CONTAINER" >/dev/null 2>&1 \
  || die "database container $CONTAINER is not running on this host"
psql_run() { docker exec -i "$CONTAINER" psql -X -q -v ON_ERROR_STOP=1 -U "$DBUSER" -d "$DB" "$@"; }
query() { printf '%%s\n' "$1" | psql_run -At; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
tar -xzf "$HERE/%s" -C "$WORK"

NAMES=(); SHAS=(); OWNTX=(); DESTR=()
while IFS=$'\t' read -r name sha own destr; do
  [ -n "$name" ] || continue
  NAMES+=("$name"); SHAS+=("$sha"); OWNTX+=("$own"); DESTR+=("$destr")
  actual="$(sha256sum "$WORK/$name" | cut -d' ' -f1)"
  [ "$actual" = "$sha" ] || die "$name does not match the uploaded plan (checksum differs)"
done <<'MANIFEST'
%sMANIFEST
[ "${#NAMES[@]}" -gt 0 ] || die "no migration files in the plan"
if [ -n "$THROUGH" ]; then
  found=0; for n in "${NAMES[@]}"; do [ "$n" = "$THROUGH" ] && found=1; done
  [ "$found" = 1 ] || die "--through $THROUGH is not one of the migration files"
fi

psql_run <<'SQL'
create table if not exists public.schema_migrations (
  filename text primary key,
  sha256 text not null,
  applied_at timestamptz not null default now(),
  how text not null
);
SQL

declare -A IS_APPLIED=()
APPLIED=0
while IFS= read -r line; do
  [ -n "$line" ] || continue
  IS_APPLIED["$line"]=1; APPLIED=$((APPLIED + 1))
done < <(query "select filename from public.schema_migrations")

PENDING=()
for i in "${!NAMES[@]}"; do [ -z "${IS_APPLIED[${NAMES[$i]}]:-}" ] && PENDING+=("$i"); done

user_tables() {
  query "select count(*) from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where c.relkind in ('r','p') and n.nspname not in ('pg_catalog','information_schema')
      and n.nspname not like 'pg\_toast%%'
      and not (n.nspname = 'public' and c.relname = 'schema_migrations')
      and not exists (select 1 from pg_depend d where d.classid = 'pg_class'::regclass and d.objid = c.oid and d.deptype = 'e')"
}

WHO_SQL="$(printf '%%s' "$WHO" | sed "s/'/''/g")"
record_sql() { printf "insert into public.schema_migrations (filename, sha256, how) values ('%%s', '%%s', '%%s');\n" "$1" "$2" "$WHO_SQL"; }

case "$MODE" in
  status)
    log "Applied: $APPLIED · files: ${#NAMES[@]} · pending: ${#PENDING[@]}"
    for i in "${PENDING[@]}"; do
      flag=""; [ "${DESTR[$i]}" = true ] && flag="  [DESTRUCTIVE: needs -- allow-destructive]"
      log "  pending  ${NAMES[$i]}$flag"
    done
    if [ "$APPLIED" -eq 0 ] && [ "$(user_tables)" != 0 ]; then
      log "  note     the database already has tables but nothing is recorded: run 'eu migrate baseline' once"
    fi
    declare -A SHA_OF=()
    for i in "${!NAMES[@]}"; do SHA_OF["${NAMES[$i]}"]="${SHAS[$i]}"; done
    while IFS='|' read -r name hash; do
      [ -n "$name" ] && [ -n "${SHA_OF[$name]:-}" ] && [ "${SHA_OF[$name]}" != "$hash" ] \
        && log "  note     $name changed after it was applied"
    done < <(query "select filename, sha256 from public.schema_migrations where how <> 'baseline'")
    result "$APPLIED" "${#PENDING[@]}" 0
    ;;

  baseline)
    [ "$APPLIED" -eq 0 ] || die "baseline already done ($APPLIED files recorded). Nothing changed."
    {
      echo "begin;"
      for i in "${!NAMES[@]}"; do
        echo "insert into public.schema_migrations (filename, sha256, how) values ('${NAMES[$i]}', '${SHAS[$i]}', 'baseline');"
        [ -n "$THROUGH" ] && [ "${NAMES[$i]}" = "$THROUGH" ] && break
      done
      echo "commit;"
    } > "$WORK/baseline.sql"
    marked="$(grep -c '^insert' "$WORK/baseline.sql")"
    psql_run < "$WORK/baseline.sql"
    log "Baseline recorded: $marked file(s) marked as already applied."
    result "$marked" "$(( ${#NAMES[@]} - marked ))" 0
    ;;

  apply)
    if [ "$APPLIED" -eq 0 ] && [ "$(user_tables)" != 0 ]; then
      die "the database already has tables but no migrations are recorded. Run 'eu migrate baseline' once to mark the files that are already applied (nothing was changed)."
    fi
    if [ "${#PENDING[@]}" -eq 0 ]; then
      log "Database is up to date ($APPLIED applied)."
      result "$APPLIED" 0 0
      exit 0
    fi
    for i in "${PENDING[@]}"; do
      [ "${DESTR[$i]}" = true ] && die "${NAMES[$i]} contains DROP/TRUNCATE/DELETE. Add a line '-- allow-destructive' to the file if that is intended. Nothing was applied."
    done
    backup_path="-"
    if [ "$BACKUP" = 1 ] && [ "$APPLIED" -gt 0 ]; then
      log "Backing up $DB before migrating..."
      mkdir -p "$BACKUP_DIR"
      backup_path="$BACKUP_DIR/pre-migrate-$(date -u +%%Y%%m%%dT%%H%%M%%SZ).dump"
      docker exec "$CONTAINER" pg_dump -U "$DBUSER" -Fc "$DB" > "$backup_path" && [ -s "$backup_path" ] \
        || { rm -f "$backup_path"; die "backup failed; nothing was applied"; }
      ls -1t "$BACKUP_DIR"/pre-migrate-*.dump | tail -n +$((KEEP + 1)) | xargs -r rm -f
      log "Backup: $backup_path ($(du -h "$backup_path" | cut -f1))"
    fi
    ran=0
    for i in "${PENDING[@]}"; do
      f="${NAMES[$i]}"
      log "Applying $f"
      if [ "${OWNTX[$i]}" = true ]; then
        psql_run < "$WORK/$f" || die "$f failed. Later files were not applied."
        record_sql "$f" "${SHAS[$i]}" | psql_run \
          || die "$f applied but could not be recorded; record it manually before the next deploy."
      else
        { echo "begin;"; cat "$WORK/$f"; echo; record_sql "$f" "${SHAS[$i]}"; echo "commit;"; } | psql_run \
          || die "$f failed and was rolled back. Later files were not applied."
      fi
      [ "$(query "select count(*) from public.schema_migrations where filename = '$f'")" = 1 ] \
        || die "$f did not complete (no record after running it). Later files were not applied."
      ran=$((ran + 1))
    done
    log "Applied $ran migration(s)."
    result "$((APPLIED + ran))" 0 "$ran" "$backup_path"
    ;;

  *) die "usage: migrate.sh status|apply|baseline [through-file]" ;;
esac
`,
		shellQuote(o.Container), shellQuote(o.Database), shellQuote(o.User), backup,
		shellQuote(o.BackupDir), keep,
		ResultPrefix,
		ArchiveName,
		manifest.String(),
	)
}
